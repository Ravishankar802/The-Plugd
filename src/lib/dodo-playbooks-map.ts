export function getPlaybookDodoMapping(slugOrId: string): DodoPlaybookMapping | null {
  if (!slugOrId) return null;
  const clean = slugOrId.trim().toLowerCase();
  const mode = process.env.DODO_PAYMENTS_MODE?.trim();

  if (mode === "test_mode") {
    // In test_mode, ONLY the representative test playbook is active. All other 108 playbooks fail closed.
    if (clean === TEST_MODE_PLAYBOOK_SLUG || clean === TEST_MODE_PLAYBOOK_ID) {
      return getTestModePlaybookMapping();
    }
    return null;
  }

  // In live_mode (or default): use authoritative live mapping
  return DODO_PLAYBOOK_MAP[clean] || DODO_ID_TO_PLAYBOOK[clean] || null;
}

export function getPlaybookByDodoProductId(productId: string): DodoPlaybookMapping | null {
  if (!productId) return null;
  const cleanId = productId.trim();
  const mode = process.env.DODO_PAYMENTS_MODE?.trim();

  if (mode === "test_mode") {
    const testMapping = getTestModePlaybookMapping();
    if (testMapping && cleanId === testMapping.dodoProductId) {
      return testMapping;
    }
    // Any live product ID in test_mode is strictly rejected
    return null;
  }

  // In live_mode:
  // If the product ID is the test product ID or starts with test prefix, strictly reject
  const testProductId = process.env.DODO_TEST_PLAYBOOK_PRODUCT_ID?.trim();
  if (testProductId && cleanId === testProductId) {
    return null;
  }
  if (cleanId.startsWith("pdt_test_")) {
    return null;
  }

  return DODO_PRODUCT_TO_PLAYBOOK[cleanId] || null;
}
