// Reverse lookup map: dodoProductId -> DodoPlaybookMapping
export const DODO_PRODUCT_TO_PLAYBOOK: Record<string, DodoPlaybookMapping> = Object.values(
  DODO_PLAYBOOK_MAP
).reduce((acc, item) => {
  acc[item.dodoProductId] = item;
  return acc;
}, {} as Record<string, DodoPlaybookMapping>);

// Also index by playbookId (e.g. ai-businesses-01) for fast id resolution
export const DODO_ID_TO_PLAYBOOK: Record<string, DodoPlaybookMapping> = Object.values(
  DODO_PLAYBOOK_MAP
).reduce((acc, item) => {
  acc[item.playbookId] = item;
  return acc;
}, {} as Record<string, DodoPlaybookMapping>);

