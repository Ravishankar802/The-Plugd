/** Process products with images and display order */
export function getFullDrinksCatalog(): DrinksProduct[] {
  const productMap = new Map(RAW_DRINKS_PRODUCTS.map((p) => [p.id, p]));
  
  return DRINKS_SECTIONS.flatMap((section) => 
    section.productIds
      .map((id) => productMap.get(id))
      .filter((product): product is DrinksProduct => product !== undefined)
      .map((product, index) => ({
        ...product,
        category: "Food & Drinks",
        imageUrl: getDrinksProductImage(product.id) || DEFAULT_DRINKS_IMAGE,
        displayOrder: section.displayOrder * 1000 + index,
      }))
  );
}
